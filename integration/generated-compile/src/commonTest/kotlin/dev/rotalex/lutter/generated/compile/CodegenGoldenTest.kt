/**
 * PLAN §36.1: the documents that generate the Kotlin this module compiles also generate a committed
 * golden, and the two are compared byte for byte.
 *
 * Compiling the generated screens is the other half of that sentence and it is already a fact on
 * every build — but a compile check answers one question, and it is not the one a golden asks. It
 * says the output is Kotlin a compiler accepts; it says nothing about whether it is the output
 * anybody agreed to. A screen can keep compiling while its layout flips from a weight to a fixed
 * height, and `CanonicalJsonGoldenTest`'s own KDoc is the argument in full: only a committed file
 * a reviewer read notices that.
 *
 * ### Where the input comes from
 *
 * The fixture JSON is read out of the constants `GenerateFixtures` already embeds in `commonMain`,
 * not off the filesystem. Three reasons and the first is the one that matters: these are the exact
 * bytes this module's `commonMain` was generated from, so a golden and the compiled sources can
 * never be describing different documents. `commonTest` runs on two host targets and has no
 * filesystem worth reading — and a `File` read at execution time would be an untracked input, which
 * `org.gradle.configuration-cache.problems=fail` is set in both property files to refuse.
 *
 * ### The format, and why the marker is safe
 *
 * One golden per fixture, holding **every** file that fixture generates, each behind a
 * `### file: <path>` marker line:
 *
 * ```
 * ### file: App.kt
 * // Generated by Forge. Do not edit.
 * package dev.rotalex.lutter.generated.spacer_size
 * …
 * ### file: AppHost.kt
 * …
 * ```
 *
 * The file order **is** `GeneratedFiles.files`, which sorts by path. The sort is the reason this
 * golden is stable and the reason the format says so: a generator that stopped sorting would
 * reorder all eleven goldens at once, and nothing but this sentence would say that had happened.
 *
 * A marker line cannot collide with generated Kotlin, and the strongest reason is one this module
 * already enforces every build: these generated files are compiled into `commonMain`, `#` is not a
 * Kotlin token, and a line-initial `#` would not compile. Mechanically the same claim holds from
 * the printer's side — every line `KtPrinter` breaks is the header comment, a package or import
 * line, an annotation, a declaration opening with a visibility keyword, an indented continuation,
 * or a closing brace, and the only document-authored text that can reach output goes through
 * `LiteralPrinter.escape`, which writes a newline as two characters, so no document string opens
 * a line either. `GenerateCodegenGoldens` re-checks it per run rather than trusting the argument.
 *
 * ### The split, and why the goldens do not exist yet
 *
 * A golden is written by one task and one only: `generateCodegenGoldens` forks the CLI, frames
 * what it wrote, and writes the file. `Golden.assertEquals(..., update = true)` is the mechanism
 * this repository already has for getting that text — the task is its writer, so there is one of
 * them and not two. Until the task runs, **every fixture row below is red**, each with
 * `Golden.read`'s "No golden file named …". That is the designed behaviour: an absent golden is an
 * authoring error, not a mismatch, and weakening `Golden` to make a first run green would destroy
 * the distinction.
 *
 * ### One row per fixture
 *
 * Eleven rows rather than one over the set. The cost is the same either way — each fixture is
 * decoded, analyzed and generated exactly once whichever shape the loop takes — and eleven rows
 * name the eleven fixtures in a CI report, where one row over the set is a single failure whose
 * message somebody has to read before knowing which fixture moved.
 */
