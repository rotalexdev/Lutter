    /**
     * The harness covers what is on disk, and says the count when it does not.
     *
     * A golden harness that compares zero fixtures passes and means nothing, so the number of
     * rows is pinned against the number of documents the two fixture directories actually hold. A
     * fixture added without a row fails here, naming itself, rather than being covered by
     * nothing — and one of the two directories is `fixtures-navigating`, which `FixtureValidationTest`
     * does not reach, so this row is where its single document is accounted for.
     *
     * The list rather than a bare count because the list is the claim, the same reason
     * `FixtureValidationTest` spells its ten out. What this cannot see is the opposite drift — an
     * entry here with no row above it — which is a reading of this file rather than an assertion
     * about it, and saying so is cheaper than reflection in a test about goldens.
     */
    @Test
    fun `a row exists for every fixture on disk, and every fixture has one golden`() {
        val onDisk = (FixtureDocuments.ids + NavigatingFixtureDocuments.ids).sorted()

        assertEquals(
            GOLDEN_FIXTURES.sorted(),
            onDisk,
            "CodegenGoldenTest compares ${GOLDEN_FIXTURES.size} fixtures and the two fixture " +
                "directories hold ${onDisk.size}. Every fixture needs a row and a golden: $onDisk",
        )
    }

    /**
     * One fixture, generated and compared.
     *
     * Four steps in the order they can each be the one that fails. [Golden.read] comes before the
     * generation because an absent golden is the first run's failure and it is `read`'s message,
     * not a diff of four thousand lines against nothing. The per-file comparison comes before
     * [Golden.assertEquals] because `assertEquals` raises the whole text and says which fixture
     * moved but not which of its four files did — and a file's name is the first thing anybody
     * looks for. [Golden.assertEquals] is last because it is the authority: it holds the whole
     * bytes, it is what names the golden, and it is where `update = true` would be passed.
     */
    private fun fixture(id: String) {
        val name = GOLDEN_DIRECTORY + id + ".golden"
        val source = classpathGoldenSource()
        val golden = Golden.read(name, source)
        val generated = generate(id)

        assertNotTrivial(id, golden)
        reportFirstDifference(id, parse(id, golden), generated)
        Golden.assertEquals(name, render(generated), source)
    }

    /**
     * The golden is a whole fixture's output, not a token.
     *
     * `Golden.read` already refuses an absent golden, which is the common authoring error; this
     * refuses the second one, a golden that is present and empty. The floor is far below the
     * smallest of the eleven — each generates `App.kt`, `Navigation.kt`, `AppHost.kt` and a
     * screen at minimum — so it can only ever catch a truncated or header-only write.
     */
    private fun assertNotTrivial(id: String, golden: String) {
        assertTrue(
            golden.length >= MINIMUM_GOLDEN_LENGTH,
            "Golden for '$id' is ${golden.length} characters and no fixture is under " +
                "$MINIMUM_GOLDEN_LENGTH. An empty or one-line golden is an authoring error, and it " +
                "would otherwise compare equal for as long as the generator kept emitting nothing.",
        )
    }

    /**
     * The file a mismatch is in, named before `assertEquals` gets to raise the whole text.
     *
     * The paths are compared first because a fixture that grew or lost a file is a different
     * failure from one whose bytes moved, and the message carries both counts. The first differing
     * line is reported because the file name narrows thousands of characters to hundreds, and the
     * line narrows those to one.
     */
    private fun reportFirstDifference(id: String, stored: List<GeneratedFile>, generated: List<GeneratedFile>) {
        assertEquals(
            generated.map { it.path },
            stored.map { it.path },
            "Golden for '$id' holds ${stored.size} files and '$id' generated ${generated.size}",
        )
        for (expected in stored) {
            val actual = generated.first { it.path == expected.path }
            if (expected.content == actual.content) continue
            val line = firstDifferingLine(expected.content, actual.content)
            fail(
                "Generated file '${expected.path}' of fixture '$id' differs from its golden at " +
                    "line $line: golden has ${atLine(expected.content, line)}, generated has " +
                    "${atLine(actual.content, line)}",
            )
        }
    }

    /** One-based line [text] either holds at [line], or a note that it runs no longer than that. */
    private fun atLine(text: String, line: Int): String {
        val held = text.lines().getOrNull(line - 1)
        return if (held == null) "no line $line" else "'$held'"
    }

    /** The first line the two texts disagree on, or 0 when they do not disagree at all. */
    private fun firstDifferingLine(golden: String, generated: String): Int {
        val left = golden.lines()
        val right = generated.lines()
        for (index in 0 until maxOf(left.size, right.size)) {
            if (left.getOrNull(index) != right.getOrNull(index)) return index + 1
        }
        return 0
    }

    /**
     * The fixture decoded, analyzed and generated — the three steps `GenerateCommand` runs, in
     * that order, through the same public API it uses.
     *
     * The analysis diagnostics are handed to `generate` for the reason the CLI hands them over:
     * a result carrying an error is empty files, and the generator must see them to say so. There
     * are none, which is asserted rather than assumed — `FixtureValidationTest` says the same
     * thing about the documents, and a golden compared against a refused generation would pin the
     * refusal.
     */
    private fun generate(id: String): List<GeneratedFile> {
        val schema = ConformanceHarness.schema()
        val result = ConformanceHarness.analyze(schema, id, documents(id))
        assertTrue(result.diagnostics.isEmpty(), "fixture '$id': ${result.diagnostics}")
        val resolved = assertNotNull(result.resolved, "fixture '$id' resolved nothing")

        val generated = KotlinGenerator(schema, CodegenOptions(GENERATED_PACKAGE + id))
            .generate(resolved, result.diagnostics)
        assertTrue(
            generated.diagnostics.none { it.severity == Severity.Error },
            "fixture '$id' refused to generate: ${generated.diagnostics}",
        )
        return generated.files.files
    }

    /**
     * The fixture's own JSON, from whichever of the two generated objects holds it.
     *
     * The navigating fixture is a separate object because `GenerateFixtures` emits it into its own
     * directory, and asking the wrong one throws rather than returning empty — which is the
     * failure a fixture added to the wrong directory gets.
     */
    private fun documents(id: String): (String) -> String =
        if (id in NavigatingFixtureDocuments.ids) {
            NavigatingFixtureDocuments::json
        } else {
            FixtureDocuments::json
        }

    /** Every file this fixture generated, in `GeneratedFiles` order, framed by its marker. */
    private fun render(files: List<GeneratedFile>): String = buildString {
        for (file in files) {
            appendLine(MARKER + file.path)
            append(file.content)
        }
    }

    /**
     * The same format read back.
     *
     * A line that opens a block runs until the next marker, because no generated line can begin
     * with one — which is the whole of the collision argument, asserted here as a parse failure
     * rather than left to the reader. Each block is rejoined with the newline that framed it, so
     * what comes back is the file's own bytes rather than a split of them.
     *
     * The `dropLast` is load-bearing and is why the trailing newline is asserted first: a golden
     * ending in one splits into a final empty line, and that empty line is the last file's own
     * terminator. Keeping it would give the last file a second newline and fail a comparison that
     * is in fact byte-exact.
     */
    private fun parse(id: String, text: String): List<GeneratedFile> {
        assertTrue(text.endsWith("\n"), "Golden for '$id' does not end in a newline, so its framing is lost")
        val lines = text.split("\n").dropLast(1)
        val parsed = mutableListOf<GeneratedFile>()
        var index = 0
        while (index < lines.size) {
            val header = lines[index]
            assertTrue(
                header.startsWith(MARKER),
                "Golden for '$id' line ${index + 1} is '$header', which opens no file",
            )
            val body = index + 1
            index = body
            while (index < lines.size && !lines[index].startsWith(MARKER)) index += 1
            parsed += GeneratedFile(
                header.removePrefix(MARKER),
                lines.subList(body, index).joinToString("\n") + "\n",
            )
        }
        return parsed
    }

    private companion object {
        /** The classpath root Gradle already publishes this module's `commonTest` resources from. */
        const val GOLDEN_DIRECTORY: String = "goldens/"

        /**
         * The prefix `GenerateFixtures` hands the CLI, spelled the way `NavigationFixtureTest`
         * spells it. The task sanitises an id before appending it and this does not, and for all
         * eleven ids the sanitising is the identity — a fixture needing it would leave the golden
         * stale, which is the right signal and the wrong surprise.
         */
        const val GENERATED_PACKAGE: String = "dev.rotalex.lutter.generated."

        /**
         * Shared with `GenerateCodegenGoldens` by spelling. It cannot be a declaration the two
         * share, because the task cannot see `commonTest` and `:engine:test-support` is not a build
         * input — so the constant is written twice and the golden is what notices a disagreement.
         */
        const val MARKER: String = "### file: "

        /** Far below the smallest of the eleven; see [assertNotTrivial]. */
        const val MINIMUM_GOLDEN_LENGTH: Int = 512

        /** Every fixture a row above compares, which is every fixture on disk. */
        val GOLDEN_FIXTURES: List<String> = listOf(
            "box_align",
            "column_color",
            "column_text",
            "component_param_slot",
            "expression_corpus",
            "material_token",
            "row_weight",
            "spacer_size",
            "text_field_state",
            "theme_tokens",
            "button_navigate",
        )
    }
}