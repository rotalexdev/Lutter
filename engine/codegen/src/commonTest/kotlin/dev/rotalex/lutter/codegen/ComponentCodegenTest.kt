/**
 * §5.5's component, as the generator writes it: a function with declared params, and a call that
 * passes them.
 *
 * Over hand-built resolved documents, so every input is spelled out — in particular
 * `componentSpecs`, which is what a real [dev.rotalex.lutter.analysis.Analyzer] carries and what
 * makes the two goldens below about *this* generator rather than about a fixture.
 *
 * The specs are built with `documentComponentSpec`, the function `SchemaOverlay` itself calls, so
 * a test cannot pass against a hand-written spec that the analyzer would never synthesize.
 */
class ComponentCodegenTest {

    private val columnType: ComponentType = ComponentType("test.Column")
    private val textType: ComponentType = ComponentType("test.Text")
    private val pressType: ComponentType = ComponentType("test.Press")
    private val outletType: ComponentType = ComponentType("core.SlotOutlet")
    private val badgeId: ComponentDeclId = ComponentDeclId("c_badge")
    private val badgeType: ComponentType = ComponentType("doc.c_badge")
    private val pageId: PageId = PageId("p_home")
    private val labelKey: PropertyKey = PropertyKey("label")
    private val textKey: PropertyKey = PropertyKey("text")
    private val slotKey: PropertyKey = PropertyKey("slot")
    private val contentSlot: SlotName = SlotName("content")
    private val childrenSlot: SlotName = SlotName("children")
    private val clickKey: EventKey = EventKey("onClick")

    // The one handler the receiver test needs: `ui.showSnackbar` reaches the host the screen has
    // to supply, which is the whole of what `environmentParams` exists for.
    private val showSnackbar: ActionSpec = ActionSpec(
        id = ActionId("ui.showSnackbar"),
        metadata = ActionMetadata("Show snackbar"),
        params = listOf(prop<String>("message", TypeRef.Str, required = true)),
        emit = ActionEmit.Intrinsic,
    )

    @Test
    fun `a document component is a function whose params and slots are its declaration's`() {
        val result = generate(badge())

        assertTrue(result.diagnostics.isEmpty(), "got ${result.diagnostics}")
        assertEquals(
            """
            // Generated by Forge. Do not edit.
            package com.example.app.components

            ${"import"} androidx.compose.foundation.layout.Column
            ${"import"} androidx.compose.material3.Text
            ${"import"} androidx.compose.runtime.Composable
            ${"import"} androidx.compose.ui.Modifier

            @Composable
            public fun c_badge(label: String, modifier: Modifier = Modifier, content: @Composable () -> Unit = {}) {
                Column(
                    modifier = modifier,
                ) {
                    Text(label)
                    content()
                }
            }

            """.trimIndent(),
            content(result, "components/c_badge.kt"),
        )
    }

    @Test
    fun `an instance is a call that passes the declared params and the filled slot`() {
        val result = generate(badge())

        assertTrue(result.diagnostics.isEmpty(), "got ${result.diagnostics}")
        assertEquals(
            """
            // Generated by Forge. Do not edit.
            package com.example.app.screens

            ${"import"} androidx.compose.foundation.layout.Column
            ${"import"} androidx.compose.material3.Text
            ${"import"} androidx.compose.runtime.Composable
            ${"import"} androidx.compose.ui.Modifier
            ${"import"} com.example.app.components.c_badge

            @Composable
            public fun HomeScreen(modifier: Modifier = Modifier) {
                Column(
                    modifier = modifier,
                ) {
                    c_badge(
                        label = "Live",
                        modifier = Modifier,
                    ) {
                        Text("body")
                    }
                }
            }

            """.trimIndent(),
            content(result, "screens/HomeScreen.kt"),
        )
    }

    /**
     * The reason the instantiation site passes receivers: a component function's handlers name the
     * same receivers a screen's do, and the call is what carries them down.
     *
     * Before this the generator drained a component's reads and threw them away, on the stated
     * ground that nothing called a component function. Now something does, so they are declared on
     * the component and passed by name at every call site — which is also what makes the screen
     * declare them, since the argument resolves to a parameter of the caller.
     */
    @Test
    fun `a component's receiver is declared on it and passed by its caller`() {
        val result = generate(badge(defaultBody(withPress = true)))

        assertTrue(result.diagnostics.isEmpty(), "got ${result.diagnostics}")
        val component = content(result, "components/c_badge.kt")
        assertTrue(
            component.contains(
                "public fun c_badge(" +
                    "label: String, snackbars: SnackbarHost, " +
                    "modifier: Modifier = Modifier, content: @Composable () -> Unit = {}) {",
            ),
            component,
        )
        assertTrue(component.contains("snackbars.show(\"Saved\")"), component)

        val screen = content(result, "screens/HomeScreen.kt")
        assertTrue(
            screen.contains("public fun HomeScreen(snackbars: SnackbarHost, modifier: Modifier = Modifier) {"),
            screen,
        )
        assertTrue(screen.contains("snackbars = snackbars,"), screen)
    }

    /**
     * Kotlin binds a call's trailing lambda to the signature's last parameter, so a multi-slot
     * component call spells the earlier slots by name and leaves the last slot's lambda trailing.
     * The old rule trailed the first bound slot instead; beside a named last one that is the
     * "Too many arguments" diagnostic the fuzz batch minted on every slot-heavy component.
     */
    @Test
    fun `a multi slot call keeps the last slot's lambda trailing`() {
        val actionsSlot = SlotName("actions")
        val result = generate(
            badge(
                slots = listOf(SlotDecl(contentSlot), SlotDecl(actionsSlot)),
                instance = instance(
                    "Live",
                    slots = mapOf(
                        contentSlot to listOf(textNode("n_filled", "body")),
                        actionsSlot to listOf(textNode("n_action", "press")),
                    ),
                ),
            ),
        )

        assertTrue(result.diagnostics.isEmpty(), "got ${result.diagnostics}")
        val screen = content(result, "screens/HomeScreen.kt")
        assertTrue(screen.contains("content = {"), screen)
        assertFalse(screen.contains("actions = "), screen)
        assertTrue(screen.contains("Text(\"press\")"), screen)
    }

    /**
     * A component that instantiates itself has no file order, and the runtime reports that at
     * render time — so codegen reports it here rather than picking an order and emitting a call
     * that passes a receiver its callee never got.
     */
    @Test
    fun `an instantiation cycle is refused rather than ordered`() {
        val result = generate(
            badge(
                body = column(
                    "n_self",
                    listOf(
                        ResolvedNode(
                            NodeId("n_again"),
                            badgeType,
                            mapOf(labelKey to string(labelKey, "again")),
                            emptyList(),
                            emptyMap(),
                            emptySet(),
                        ),
                    ),
                ),
            ),
        )

        assertTrue(result.diagnostics.any { it.severity == Severity.Error }, "${result.diagnostics}")
        assertTrue(
            result.diagnostics.any { it.message.contains("instantiation cycle") },
            "${result.diagnostics}",
        )
        assertTrue(result.files.files.isEmpty(), "a refused document emits files")
    }

    /**
     * `ParamDecl` carries no default value, so a declared parameter has nothing to be defaulted
     * from and an instance that omits one is refused rather than emitting a call the generated
     * function's signature cannot accept.
     */
    @Test
    fun `an instance omitting a declared param is refused rather than half-written`() {
        val result = generate(
            badge(
                instance = ResolvedNode(
                    NodeId("n_badge"),
                    badgeType,
                    emptyMap(),
                    emptyList(),
                    emptyMap(),
                    emptySet(),
                ),
            ),
        )

        assertTrue(result.diagnostics.any { it.severity == Severity.Error }, "${result.diagnostics}")
        assertTrue(
            result.diagnostics.any { it.message.contains("omits parameter 'label'") },
            "${result.diagnostics}",
        )
    }

    /**
     * The instance call always names the modifier argument, even when the node carries no
     * entries: the callee the call reaches is the generated function, whose signature was
     * already written with a default, so the compiler has nothing to fall back on at the call
     * site — "No value passed for parameter 'modifier'" is what an omission compiles into
     * there. The argument spelled is the untouched `Modifier`, the same base a leaf with an
     * update chain builds on.
     */
    @Test
    fun `an instance call spells its modifier argument even with no entries`() {
        val result = generate(badge())

        assertTrue(result.diagnostics.isEmpty(), "got ${result.diagnostics}")
        val screen = content(result, "screens/HomeScreen.kt")
        // Args at the call's own indent, the close back at the call's: the same columns the
        // `C_badge` golden above prints the call with.
        assertTrue(
            "c_badge(\n            label = \"Live\",\n            modifier = Modifier,\n        ) {" in screen,
            screen,
        )
    }

    /**
     * The slot outlet is engine-owned, so `emitNode` used to refuse it and a component body could
     * not be emitted at all. It writes the call to the slot's own parameter — the generated twin of
     * the runtime asking the open instance for the children the call site filled.
     */
    @Test
    fun `the slot outlet emits the call to the slot's parameter`() {
        assertTrue(
            content(generate(badge()), "components/c_badge.kt").contains("content()"),
            "no outlet call in the component",
        )
    }

    // -----------------------------------------------------------------------------------------
    // Documents
    // -----------------------------------------------------------------------------------------

    /**
     * One declaration, one page, one instance of the declaration.
     *
     * [body] is the declaration's root subtree; [instance] is the node on the page. The default
     * body is the shape Phase 8 is about: a `Text` that reads the declaration's own parameter, and
     * the outlet that draws the slot.
     */
    private fun badge(
        body: ResolvedNode = defaultBody(withPress = false),
        instance: ResolvedNode = instance("Live"),
        slots: List<SlotDecl> = listOf(SlotDecl(contentSlot)),
    ): ResolvedDocument {
        val decl = ComponentDecl(
            id = badgeId,
            name = "Badge",
            params = listOf(ParamDecl(ParamName("label"), TypeRef.Str)),
            slots = slots,
            root = body.id,
        )
        val pages = mapOf(pageId to ResolvedPage(pageId, "Home", "home", column("n_root", listOf(instance))))
        val components = mapOf(badgeId to body)
        val nodes = LinkedHashMap<NodeId, ResolvedNode>()
        fun walk(node: ResolvedNode) {
            nodes[node.id] = node
            for (kids in node.slots.values) kids.forEach(::walk)
        }
        pages.values.forEach { walk(it.root) }
        walk(body)
        return ResolvedDocument(
            pages = pages,
            components = components,
            nodes = nodes,
            theme = ResolvedTheme(null),
            componentSpecs = mapOf(badgeId to documentComponentSpec(decl)),
        )
    }

    /** The declaration body: the `Text` that reads the parameter, the outlet, and an optional press. */
    private fun defaultBody(withPress: Boolean): ResolvedNode {
        val children = mutableListOf(textAs("n_label", PropertyKey("label")), outlet())
        if (withPress) children += pressHandler()
        return column("n_body", children)
    }

    private fun pressHandler(): ResolvedNode =
        press("n_press", ActionSequence(listOf(ActionStep(ActionId("ui.showSnackbar"), snackbarArgs()))))

    private fun instance(
        label: String,
        slots: Map<SlotName, List<ResolvedNode>> = mapOf(contentSlot to listOf(textNode("n_filled", "body"))),
    ): ResolvedNode = ResolvedNode(
        id = NodeId("n_badge"),
        type = badgeType,
        props = mapOf(labelKey to string(labelKey, label)),
        modifiers = emptyList(),
        slots = slots,
        scopes = emptySet(),
    )

    private fun snackbarArgs(): Map<PropertyKey, PropertyValue> =
        mapOf(PropertyKey("message") to PropertyValue.Const(Value.Str("Saved")))

    private fun column(id: String, children: List<ResolvedNode>): ResolvedNode = ResolvedNode(
        NodeId(id),
        columnType,
        emptyMap(),
        emptyList(),
        mapOf(childrenSlot to children),
        emptySet(),
    )

    /**
     * A `Text` whose text is a **reference to a param**, not the string that names it.
     *
     * The constant version emitted `Text("label")` where the test expected `Text(label)`, and
     * the generator was right: §9 gives an expression-backed property a typed expression and a
     * constant-backed one a constant, and this was built as the second. A component body that
     * printed its parameter's *name* rather than its value would have passed the test and been
     * useless.
     */
    private fun textAs(id: String, key: PropertyKey): ResolvedNode = ResolvedNode(
        NodeId(id),
        textType,
        mapOf(textKey to paramAs(textKey, key)),
        emptyList(),
        emptyMap(),
        emptySet(),
    )

    private fun textNode(id: String, text: String): ResolvedNode = ResolvedNode(
        NodeId(id),
        textType,
        mapOf(textKey to string(textKey, text)),
        emptyList(),
        emptyMap(),
        emptySet(),
    )

    private fun outlet(): ResolvedNode = ResolvedNode(
        NodeId("n_outlet"),
        outletType,
        mapOf(slotKey to string(slotKey, "content")),
        emptyList(),
        emptyMap(),
        emptySet(),
    )

    private fun press(id: String, sequence: ActionSequence): ResolvedNode = ResolvedNode(
        NodeId(id),
        pressType,
        emptyMap(),
        emptyList(),
        emptyMap(),
        emptySet(),
        events = mapOf(clickKey to sequence),
    )

    private fun string(key: PropertyKey, value: String): ResolvedProp =
        ResolvedProp(key, PropertyValue.Const(Value.Str(value)), PropOrigin.Specified, null)

    /** [key] bound to the param named [target] — §9's `param.<name>` reference. */
    private fun paramAs(key: PropertyKey, target: PropertyKey): ResolvedProp {
        val reference: RefTarget = RefTarget.Param(ParamName(target.value))
        return ResolvedProp(
            key,
            PropertyValue.Computed(Expr.Ref(reference)),
            PropOrigin.Specified,
            // `token` is §14's design-token resolution and this prop names no token; `typed` is
            // the check, and it is the fifth parameter, not the fourth.
            null,
            TypedExpr(Expr.Ref(reference), ExprType.Of(TypeRef.Str), setOf(reference)),
        )
    }

    // -----------------------------------------------------------------------------------------
    // Harness
    // -----------------------------------------------------------------------------------------

    private fun generate(document: ResolvedDocument): CodegenResult =
        KotlinGenerator(schema(), CodegenOptions("com.example.app"))
            .generate(document, emptyList<Diagnostic>())

    /**
     * `core.SlotOutlet` under its real type name, because that name is what the generator's
     * intrinsic table is keyed by — the same coupling the architecture rules describe for actions.
     */
    private fun schema(): Schema<ComponentSpec, ModifierSpec, ActionSpec, FunctionSpec, String> =
        Schema.build<ComponentSpec, ModifierSpec, ActionSpec, FunctionSpec, String> {
            component(
                componentSpec(columnType, 1) {
                    metadata("Column", Category.Layout)
                    slot("children", Cardinality.Many)
                    composeCall(KotlinSymbol("androidx.compose.foundation.layout", "Column")) {
                        slot("children", LambdaTarget.Trailing)
                    }
                },
            )
            val text = prop<String>("text", TypeRef.Str, required = true)
            component(
                componentSpec(textType, 1) {
                    metadata("Text", Category.Basic)
                    property(text)
                    composeCall(KotlinSymbol("androidx.compose.material3", "Text")) {
                        param("text", from = text, positional = Positional.WhenSole)
                    }
                },
            )
            component(
                componentSpec(pressType, 1) {
                    metadata("Press", Category.Basic)
                    event("onClick")
                    composeCall(KotlinSymbol("com.example.ui", "Press")) {
                        event(clickKey, "onClick")
                    }
                },
            )
            component(
                componentSpec(outletType, 1) {
                    metadata("Slot outlet", Category.Layout)
                    property(prop<String>("slot", TypeRef.Str, required = true))
                    intrinsic()
                },
            )
            action(showSnackbar)
        }

    private fun content(result: CodegenResult, path: String): String =
        assertNotNull(
            result.files.files.firstOrNull { it.path == path },
            "no '$path' in ${result.files.files.map { it.path }}",
        ).content
}