/**
 * Event parity for the two refusals the fuzz batch refuses documents on: the missing handler
 * and the handler no binding receives.
 *
 * The specs these pin are the runtime's own behavior, and the stubs mirror the two builtins the
 * batch hit:
 *
 *   * `ButtonRenderer.Render` passes `onClick = { scope.Dispatch(node, ON_CLICK) }` whether the
 *     document wrote a handler, and `Dispatch` launches nothing for a node whose event map holds
 *     nothing for the event — so a missing handler is a *running* no-op on the runtime side, and
 *     the generated call has to spell one. The Compose parameter has no default to omit it with,
 *     so leaving the argument out would not compile; the emitter producing `{}` is what both
 *     backends run alike.
 *   * `TextFieldRenderer.Render` passes `onValueChange = {}`, and no runtime path ever dispatches
 *     a sequence the binding cannot receive, so a node event the `CodegenBinding` receives
 *     nothing for is a handler both backends run nowhere. Codegen's answer is the silence of
 *     leaving it out of the call, not `codegen.no_binding`.
 *
 * Against the generator that refused, both tests fail: the first as `codegen.strategy_unsupported`
 * (`Event 'onClick' has no handler, and 'onClick' has no default`), the second as
 * `codegen.no_binding` (`Event 'onValueChange' has no parameter to receive it`).
 */
class CodegenEventParityTest {

    private val buttonType: ComponentType = ComponentType("test.Button")
    private val textFieldType: ComponentType = ComponentType("test.TextField")
    private val textType: ComponentType = ComponentType("test.Text")
    private val valueKey: PropertyKey = PropertyKey("value")
    private val contentSlot: SlotName = SlotName("content")
    private val clickKey: EventKey = EventKey("onClick")
    private val valueChangeKey: EventKey = EventKey("onValueChange")

    @Test
    fun `a button whose handler the document wrote nowhere emits the no-op the runtime binds`() {
        val result = generate(buttonNode())

        assertTrue(result.diagnostics.isEmpty(), "got ${result.diagnostics}")
        assertEquals(
            """
            // Generated by Forge. Do not edit.
            package com.example.app.screens

            ${"import"} androidx.compose.material3.Button
            ${"import"} androidx.compose.material3.Text
            ${"import"} androidx.compose.runtime.Composable
            ${"import"} androidx.compose.ui.Modifier

            @Composable
            public fun HomeScreen(modifier: Modifier = Modifier) {
                Button(
                    onClick = {},
                    modifier = modifier,
                ) {
                    Text("Continue")
                }
            }

            """.trimIndent(),
            homeScreenOf(result),
        )
    }

    @Test
    fun `the no-op lambda keeps the parameter names its binding spells`() {
        val content = screenOf(
            generate(buttonNode(), buttonStub(listOf("pressed"))),
            "pressed no-op",
        )

        assertTrue(content.contains("onClick = { pressed -> }"), content)
    }

    @Test
    fun `a handler no binding receives is dropped, as the interpreter runs it nowhere`() {
        val result = generate(textFieldNode(droppedSequence()))

        assertTrue(result.diagnostics.isEmpty(), "got ${result.diagnostics}")
        assertEquals(
            """
            // Generated by Forge. Do not edit.
            package com.example.app.screens

            ${"import"} androidx.compose.material3.TextField
            ${"import"} androidx.compose.runtime.Composable
            ${"import"} androidx.compose.ui.Modifier

            @Composable
            public fun HomeScreen(modifier: Modifier = Modifier) {
                TextField(
                    value = "Draft",
                    modifier = modifier,
                )
            }

            """.trimIndent(),
            homeScreenOf(result),
        )
        // The drop leaves no trace beside the emitted call: no spelling of the event, and none
        // of the handler's step or the receiver the step would have asked for if it ran.
        val screen = homeScreenOf(result)
        assertTrue(!screen.contains("onValueChange"), screen)
        assertTrue(!screen.contains("showSnackbar"), screen)
        val app = contentOf(result, "App.kt")
        assertTrue(!app.contains("snackbars"), app)
    }

    private fun generate(root: ResolvedNode, button: ComponentSpec = buttonStub()): CodegenResult =
        KotlinGenerator(paritySchema(button), CodegenOptions("com.example.app"))
            .generate(homeDocument(root))

    private fun screenOf(result: CodegenResult, fixture: String): String {
        assertTrue(result.diagnostics.isEmpty(), "$fixture: ${result.diagnostics}")
        return homeScreenOf(result)
    }

    private fun homeScreenOf(result: CodegenResult): String =
        result.files.files.single { it.path == "screens/HomeScreen.kt" }.content

    private fun contentOf(result: CodegenResult, path: String): String =
        result.files.files.single { it.path == path }.content

    private fun homeDocument(root: ResolvedNode): ResolvedDocument {
        val pages = mapOf(
            PageId("p_home") to ResolvedPage(PageId("p_home"), "Home", "home", root),
        )
        return ResolvedDocument(pages, emptyMap(), indexOf(pages), ResolvedTheme(null))
    }

    private fun indexOf(pages: Map<PageId, ResolvedPage>): Map<NodeId, ResolvedNode> {
        val index = LinkedHashMap<NodeId, ResolvedNode>()
        fun walk(node: ResolvedNode) {
            index[node.id] = node
            for (kids in node.slots.values) kids.forEach(::walk)
        }
        for (page in pages.values) walk(page.root)
        return index
    }

    /** The text the button's slot holds, spelled the way `textStub` spells a `Text`. */
    private fun textNode(id: String, text: String): ResolvedNode = ResolvedNode(
        NodeId(id),
        textType,
        mapOf(
            PropertyKey("text") to ResolvedProp(
                PropertyKey("text"),
                PropertyValue.Const(Value.Str(text)),
                PropOrigin.Specified,
                null,
            ),
        ),
        emptyList(),
        emptyMap(),
        emptySet(),
    )

    private fun buttonNode(): ResolvedNode = ResolvedNode(
        NodeId("n_1"),
        buttonType,
        emptyMap(),
        emptyList(),
        mapOf(contentSlot to listOf(textNode("n_2", "Continue"))),
        emptySet(),
    )

    private fun textFieldNode(sequence: ActionSequence): ResolvedNode = ResolvedNode(
        NodeId("n_1"),
        textFieldType,
        mapOf(
            valueKey to ResolvedProp(
                valueKey,
                PropertyValue.Const(Value.Str("Draft")),
                PropOrigin.Specified,
                null,
            ),
        ),
        emptyList(),
        emptyMap(),
        emptySet(),
        mapOf(valueChangeKey to sequence),
    )

    /** A step the unbound event carries; never reached, since nothing in the schema emits it. */
    private fun droppedSequence(): ActionSequence = ActionSequence(
        listOf(
            ActionStep(
                action = ActionId("ui.showSnackbar"),
                args = mapOf(PropertyKey("message") to PropertyValue.Const(Value.Str("opened"))),
            ),
        ),
    )

    private fun paritySchema(
        button: ComponentSpec,
    ): Schema<ComponentSpec, ModifierSpec, ActionSpec, FunctionSpec, String> =
        Schema.build<ComponentSpec, ModifierSpec, ActionSpec, FunctionSpec, String> {
            component(button)
            component(textFieldStub())
            component(textStub())
        }

    /**
     * `ButtonSpec`'s binding: the press bound as the call's first argument, the label a trailing
     * lambda. `lambdaParams` mirrors what the real spec does for a handler with arguments.
     */
    private fun buttonStub(lambdaParams: List<String> = emptyList()): ComponentSpec =
        componentSpec(buttonType, 1) {
            metadata("Button", Category.Basic)
            event(clickKey.value)
            slot("content", Cardinality.Many)
            composeCall(KotlinSymbol("androidx.compose.material3", "Button")) {
                event(clickKey, "onClick", lambdaParams)
                slot("content", LambdaTarget.Trailing)
            }
        }

    /**
     * `TextFieldSpec`'s binding: the edit declared on the spec and received by no parameter,
     * which is the shape the corpus rule filters and the batch refuses on today.
     */
    private fun textFieldStub(): ComponentSpec {
        val value = prop<String>("value", TypeRef.Str, required = true)
        return componentSpec(textFieldType, 1) {
            metadata("TextField", Category.Input)
            property(value)
            event(valueChangeKey.value)
            composeCall(KotlinSymbol("androidx.compose.material3", "TextField")) {
                param("value", from = value)
            }
        }
    }

    private fun textStub(): ComponentSpec {
        val text = prop<String>("text", TypeRef.Str, required = true)
        return componentSpec(textType, 1) {
            metadata("Text", Category.Basic)
            property(text)
            composeCall(KotlinSymbol("androidx.compose.material3", "Text")) {
                param("text", from = text, positional = Positional.WhenSole)
            }
        }
    }
}
