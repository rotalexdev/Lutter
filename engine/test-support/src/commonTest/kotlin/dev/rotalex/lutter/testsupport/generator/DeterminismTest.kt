package dev.rotalex.lutter.testsupport.generator

import kotlin.random.Random
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * PLAN §36.2: *"Generated code is byte-identical across runs, across operating systems, and
 * across the engine targets (Desktop, Android) for all golden fixtures."*
 *
 * ### Which of those three halves this file can actually assert
 *
 * **Across runs: yes, and here.** Two independent pipelines over one seed, with the platform's
 * global random source disturbed between them, compared as bytes and as text. The disturbance is
 * the half that matters: `DocumentGeneratorDeterminismTest` established that a reused generator
 * consumes `Random.Default` in step with itself and so cannot see a draw from it, and the same
 * argument applies to every layer below. Burning a thousand draws between the two runs is what
 * turns "the same" into "the same despite not asking the platform for anything".
 *
 * **Across the engine targets: yes, structurally, and the mechanism is the source set.** This file
 * is in `commonTest`, so `check` runs it twice — once on the Desktop target and once on the
 * Android host test — against the same assertions over independently computed bytes. A target that
 * spelled a number differently, sorted an import differently or separated lines differently fails
 * **its own** run and the build goes red. That is a real cross-target check and it costs nothing,
 * because `forge.kmp.library` turns host tests on for exactly this reason.
 *
 * **Across operating systems: no, and nothing in this repository can.** `.github/workflows/check.yml`
 * is `runs-on: ubuntu-latest` and there is no second runner in `.github/workflows/`. A test cannot
 * observe a platform it is not executed on, so the OS half is not asserted here and is not
 * claimed. What *is* enforced, and is the half a runner-independent check can carry, is the
 * mechanism the OS claim rests on:
 *
 *  * `KtPrinter` builds every line with `StringBuilder.appendLine`, whose contract is "appends a
 *    line feed character", and every other newline in the printer is a literal `'\n'`. `println`
 *    is the stdlib call that would reach for the platform separator, and no `commonMain` file in
 *    this repository calls it. Nothing reads `System.lineSeparator`, `String.format`, `Locale` or
 *    a time zone on the way to a generated byte.
 *  * `formattingViolations` then refuses a carriage return in any emitted file **on whatever
 *    platform the runner is**. That assertion is OS-relative by construction: it enforces §16.3's
 *    LF rule on every OS that ever runs `check`, and today that is Linux only.
 *
 * So the honest statement is this: the line-ending half of the OS claim is enforced by a rule and
 * a byte check; the rest of the OS claim — anything a *platform library* does differently, which
 * is the part a source rule cannot see — is **not proven**, and `nonCanonicalNumbers` below is
 * named at the one place in this repository where it is already false. Adding a `windows-latest`
 * job that runs the same `check` is what would close the gap, and it is a workflow change rather
 * than a test.
 *
 * ### Why nothing is pinned to a committed file
 *
 * §36.2 says "for all golden fixtures", and the codegen goldens do not exist yet — `CodegenGoldenTest`
 * is §36.1's row and is still open, and `CodegenTest` compares against literals written inside the
 * test source. A committed digest is the only artefact that catches *arbitrary* divergence between
 * two targets rather than the divergence along the axes named here, and it cannot be written
 * without a run to produce it. What this file does instead is assert the invariants a divergence
 * would break, which is the part of the claim that does not need one.
 *
 * ### The failure W0 learned to ask about
 *
 * *"A test can pass while the code is broken."* Three of the cases below can pass over a corpus of
 * nothing, and the census case is the one that exists to stop it. Each case's blind spot is named
 * at its own declaration; the honest summary is that every assertion here is about **properties**,
 * not about specific bytes, and a divergence that preserved all the properties would be invisible.
 * That is the gap a golden closes and this does not.
 */
class DeterminismTest {

    /**
     * Two independent runs over one seed agree on bytes, on diagnostics and on generated files.
     *
     * Bytes and not documents, and the reason is W1's: §6.2 makes `UiDocument.equals`
     * order-independent, so a document comparison passes two things that differ where it matters.
     * `NodeTable.toString()` is `NodeTable(size=13)`, so an `assertEquals` over two documents would
     * report two renderings that are byte-identical — hence `firstByteDifference` naming the offset
     * rather than two arrays naming nothing.
     *
     * Diagnostics are compared too, and that is not decoration: a document can refuse, and two runs
     * that refuse differently are a determinism failure that a files-only comparison would not see
     * at all, because a refusal produces no files to compare.
     */
    @Test
    fun `two independent runs over one seed agree on everything`() {
        val failures = mutableListOf<String>()

        for (seed in seeds(CORPUS_SEED_COUNT)) {
            val first = outcomeOf(seed)

            // The one line that decides whether this case can see anything. `Random.Default` is
            // what a no-argument `random()`, `randomOrNull()` or `shuffled()` reads, and a
            // generator that consulted one would produce the same document twice *and* the same
            // document again after this, if the global happened not to advance in between.
            disturbThePlatformRandomSource()

            val second = outcomeOf(seed)
            failures += differences(first, second)
            if (failures.size >= REPORT_LIMIT) break
        }

        assertTrue(
            failures.isEmpty(),
            "two independent runs over ${CORPUS_SEED_COUNT} seeds disagreed.\n" +
                "A run is a function of its seed and of nothing else, including the platform's " +
                "default random source.\n" +
                failures.joinToString("\n\n"),
        )
    }

    /**
     * Every emitted file obeys §16.3's formatting rules and §16.5's path rules.
     *
     * Reported rather than asserted file by file, so one run says everything it found. The rules
     * themselves are listed at `contentViolations` and `importViolations`; this case is the one
     * that makes them load-bearing rather than documentation.
     */
    @Test
    fun `every emitted file is a well-formed source file`() {
        val failures = mutableListOf<String>()
        var checked = 0

        for (seed in seeds(CORPUS_SEED_COUNT)) {
            val outcome = outcomeOf(seed)
            if (!outcome.emitted) continue
            checked += 1
            failures += formattingViolations(outcome).map { "${outcome.describe()}\n$it" }
            if (failures.size >= REPORT_LIMIT) break
        }

        assertTrue(
            failures.isEmpty(),
            "$checked emitted file set(s) broke a printer rule.\n" + failures.joinToString("\n"),
        )
        // The same vacuity guard as the census below, on the subset that emitted: a corpus where
        // nothing was written would make the loop above check nothing and pass.
        assertTrue(checked > 0, "no seed in $CORPUS_SEED_COUNT produced a single generated file")
    }

    /**
     * Every number in generated code is a canonical decimal, with no exponent and at most four
     * fractional digits.
     *
     * The assertion §5.4's D1 makes about a document, asked of the *emitter* rather than of the
     * codec. See `nonCanonicalNumbers` for why the two are different questions and for the one the
     * corpus provably cannot answer.
     */
    @Test
    fun `every number in generated code is a canonical decimal`() {
        val failures = mutableListOf<String>()
        var checked = 0

        for (seed in seeds(CORPUS_SEED_COUNT)) {
            val outcome = outcomeOf(seed)
            if (!outcome.emitted) continue
            checked += 1
            failures += nonCanonicalNumbers(outcome).map { "${outcome.describe()}\n$it" }
            if (failures.size >= REPORT_LIMIT) break
        }

        assertTrue(
            failures.isEmpty(),
            "$checked emitted file set(s) wrote a number D1's canonical form could not have " +
                "written.\n" + failures.joinToString("\n"),
        )
        assertTrue(checked > 0, "no seed in $CORPUS_SEED_COUNT produced a single generated file")
    }

    /**
     * The files that came out are the files §16.5 planned, in the planned order.
     *
     * Checked against `planDocument` rather than against a list written out here, for the reason
     * `GenerationPlan` exists: a hand-written expected file list is a second description of what
     * the generator does, and the two drift. The planner is the engine's own answer to "which
     * files does this document have", so this asserts that the emitter wrote what it planned and
     * nothing else — which also catches a file emitted twice under two paths, since the path list
     * is compared as a list and not as a set.
     */
    @Test
    fun `the emitted file set is the one the planner declared`() {
        val failures = mutableListOf<String>()
        var checked = 0

        for (seed in seeds(CORPUS_SEED_COUNT)) {
            val outcome = outcomeOf(seed)
            if (!outcome.emitted) continue
            checked += 1
            val planned = outcome.planned.map { it.path }.sorted()
            val emitted = outcome.files.map { it.path }
            if (planned != emitted) {
                failures += "${outcome.describe()}\n  planned = $planned\n  emitted = $emitted"
            }
            if (failures.size >= REPORT_LIMIT) break
        }

        assertTrue(
            failures.isEmpty(),
            "$checked emitted file set(s) did not match §16.5's layout.\n" +
                failures.joinToString("\n\n"),
        )
        assertTrue(checked > 0, "no seed in $CORPUS_SEED_COUNT produced a single generated file")
    }

    /**
     * The corpus is worth running, and the reader is told what it is.
     *
     * Three of the four cases above iterate over "the seeds that emitted", and an empty set makes
     * every assertion inside the loop vacuously true. This case is the guard, and it has two
     * halves for that reason:
     *
     *  * **at least one seed emitted** — the floor. It cannot fail for a reason a reader cannot
     *    act on, and the census in the message says exactly how many emitted and why the rest did
     *    not, so a corpus that collapsed to one seed is visible without being a build failure.
     *  * **the corpus's plans reach every shape the generator declares it can reach** — read off
     *    `GenerationPlan`, not off the documents, because a plan survives a codegen refusal and a
     *    document does not. This is the same subset-versus-equality discipline
     *    `RoundTripPropertyTest` needed: the claim is that the corpus is varied, and a list
     *    written out here would only prove that it agrees with a list written out here.
     *
     * The shape rows are a floor too, and honestly so: they say the corpus reached these shapes,
     * not that it reached them often. What they cannot see is a corpus that reached every one of
     * them exactly once — which is why the node-count spread is here, since a corpus of documents
     * that were all the same size would satisfy every row above.
     */
    @Test
    fun `the corpus reached every shape the generator declares`() {
        val themes = mutableSetOf<ThemeSelection>()
        var declaredComponents = 0
        var instantiatedComponents = 0
        var computedProperties = 0
        var handlers = 0
        var hostCalls = 0
        var navigations = 0
        var branchedActions = 0
        var derivedStates = 0
        var smallest = Int.MAX_VALUE
        var largest = 0
        var emitted = 0

        for (seed in seeds(CORPUS_SEED_COUNT)) {
            val generated = DocumentGenerator(codegenCorpusView, seed).generate()
            val plan = generated.plan
            themes += plan.theme
            if (plan.declaredComponents.isNotEmpty()) declaredComponents += 1
            if (plan.instantiatedComponents.isNotEmpty()) instantiatedComponents += 1
            computedProperties += plan.computedProperties
            handlers += plan.handlers
            hostCalls += plan.hostCalls.size
            navigations += plan.navigations.size
            branchedActions += plan.branchedActions.size
            derivedStates += plan.derivedStates.size
            val size = generated.document.nodes.size
            smallest = minOf(smallest, size)
            largest = maxOf(largest, size)
            if (outcomeOf(generated).emitted) emitted += 1
        }

        val census = "seeds 0 until $CORPUS_SEED_COUNT; $emitted emitted code; " +
            "nodes $smallest to $largest; themes ${themes.sorted()}; " +
            "components declared in $declaredComponents and instantiated in $instantiatedComponents"

        assertTrue(emitted > 0, "no seed in $CORPUS_SEED_COUNT produced a single generated file.\n$census")
        assertEquals(ThemeSelection.entries.toSet(), themes, "the corpus missed a token-resolution rule\n$census")
        assertTrue(declaredComponents > 0, "no document declared a component\n$census")
        assertTrue(
            instantiatedComponents > 0,
            "no document placed a doc component instance, so §8.4's overlay never reached codegen\n$census",
        )
        assertTrue(computedProperties > 0, "no property was written as a computed expression\n$census")
        assertTrue(handlers > 0, "no event handler was written\n$census")
        assertTrue(hostCalls > 0, "no host call was written, so the generated AppHost declares nothing\n$census")
        assertTrue(navigations > 0, "no navigation step was written, so no page became a route\n$census")
        assertTrue(branchedActions > 0, "no action ran inside a branch arm\n$census")
        assertTrue(derivedStates > 0, "no derived declaration was written\n$census")
        assertTrue(largest > smallest, "every document had the same node count\n$census")
    }

    /**
     * Advances the platform's default random source a long way between two runs.
     *
     * Mutating a JVM global from a test is impolite in general and harmless here:
     * `kotlin.random.Random.Default` is a plain PRNG that nothing in this repository seeds from,
     * so advancing it changes only what the *next* reader of it gets — which is the point.
     */
    private fun disturbThePlatformRandomSource() {
        repeat(DISTURBANCE) { Random.nextInt() }
    }

    /** Everything two runs disagreed about, as text. Empty when they agreed about everything. */
    private fun differences(left: CorpusOutcome, right: CorpusOutcome): List<String> {
        val reported = mutableListOf<String>()
        if (!left.documentBytes.contentEquals(right.documentBytes)) {
            reported += "seed ${left.seed}: the canonical bytes differ (${left.documentBytes.size} " +
                "against ${right.documentBytes.size})\n${firstByteDifference(left.documentBytes, right.documentBytes)}"
        }
        if (left.analysisDiagnostics != right.analysisDiagnostics) {
            reported += "seed ${left.seed}: the analysis diagnostics differ\n" +
                "  first = ${left.analysisDiagnostics}\n  second = ${right.analysisDiagnostics}"
        }
        if (left.codegenDiagnostics != right.codegenDiagnostics) {
            reported += "seed ${left.seed}: the codegen diagnostics differ\n" +
                "  first = ${left.codegenDiagnostics}\n  second = ${right.codegenDiagnostics}"
        }
        if (left.files.map { it.path } != right.files.map { it.path }) {
            reported += "seed ${left.seed}: the emitted paths differ\n" +
                "  first = ${left.files.map { it.path }}\n  second = ${right.files.map { it.path }}"
        } else {
            for ((first, second) in left.files.zip(right.files)) {
                if (first.content != second.content) {
                    reported += "seed ${left.seed}: '${first.path}' differs\n" +
                        firstByteDifference(first.content.encodeToByteArray(), second.content.encodeToByteArray())
                }
            }
        }
        return reported
    }

    private companion object {

        /**
         * How many seeds this corpus runs.
         *
         * §36.2 gives no number for this row, and W0's own note is the right guide: shapes
         * saturate early and the tail buys independence rather than variety. Each seed costs two
         * full pipelines here (analysis, codegen and a canonical encode, twice), and the other
         * three cases pay for their own, so this is the largest multiplier in the file and the
         * one to lower first if the suite grows slow. A hundred and twenty contiguous seeds from
         * zero is a hundred and twenty *different* documents rather than a hundred draws that
         * might collide.
         */
        const val CORPUS_SEED_COUNT: Int = 120

        /**
         * Draws burned from the platform's default random source between two runs.
         *
         * A thousand is far more than one document makes, so anything still reading the global
         * lands somewhere unrelated. It costs microseconds.
         */
        const val DISTURBANCE: Int = 1_000

        /** Enough failures to show every distinct cause, few enough to stay readable. */
        const val REPORT_LIMIT: Int = 5
    }
}